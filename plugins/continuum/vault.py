def strip_accents(s):
    return "".join(c for c in unicodedata.normalize("NFD", s.lower()) if unicodedata.category(c) != "Mn")


def slug(text):
    s = re.sub(r"[^a-z0-9]+", "-", strip_accents(text)).strip("-")
    return s[:60] or "note"


def task_path(task):
    """'My task' -> 'tasks/my-task'; 'tasks/x' stays as is."""
    rel = task.strip().replace("\\", "/")
    return rel if rel.startswith("tasks/") else "tasks/" + slug(rel)


def project_root(base):
    """The closest folder upwards that has .git; if none, the base itself."""
    base = Path(base).resolve()
    for p in (base, *base.parents):
        if (p / ".git").exists():
            return p
    return base


def conf_get(plugin, key, base=None):
    """Last value of `<plugin>.<key>=` in the project's .claude/claude-workbench.conf ('' if none)."""
    base = Path(base or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())
    for folder in dict.fromkeys((base, project_root(base))):
        try:
            lines = (folder / CONF_FILE).read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        found = ""
        for line in lines:
            m = re.match(rf"^\s*{re.escape(plugin)}\.{re.escape(key)}\s*=\s*(.*?)\s*$", line)
            if m:
                found = m.group(1)
        if found:
            return found
    return ""


def option_on(plugin, key, base=None, default=True):
    """A boolean option: project conf wins, then the user option (CLAUDE_PLUGIN_OPTION_<KEY>), then the default."""
    value = conf_get(plugin, key, base) or os.environ.get(f"CLAUDE_PLUGIN_OPTION_{key.upper()}", "")
    if not value:
        return default
    return value.strip().lower() not in ("false", "0", "no", "off")


def find_vault(base=None):
    """Path of the vault (it may not exist yet: whoever uses it must check)."""
    if os.environ.get("CONTINUUM_VAULT"):
        return Path(os.environ["CONTINUUM_VAULT"]).resolve()
    base = base or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    root = project_root(base)
    configured = conf_get("continuum", "vault", base)
    if configured:
        p = Path(configured).expanduser()
        return (p if p.is_absolute() else root / p).resolve()
    if root.name.endswith(SUFFIX):
        return root
    return root.parent / (root.name + SUFFIX)


def language(vault):
    try:
        lang = json.loads((Path(vault) / LANG_FILE).read_text(encoding="utf-8")).get("language", "")
    except (OSError, ValueError, AttributeError):
        return DEFAULT_LANGUAGE
    return lang if lang in LABELS else DEFAULT_LANGUAGE


def label(vault, key, **fmt):
    text = LABELS[language(vault)][key]
    return text.format(**fmt) if fmt else text
