"""Where the vault is, how tasks are named and in which language the code writes: shared by the MCP and the hook.

Vault location, highest priority first:
  1. CONTINUUM_VAULT              environment variable (for tests)
  2. continuum.vault=<folder>     line in <project>/.claude/claude-workbench.conf (relative paths: from the project root)
  3. convention: the project `<parent>/x/` (root of its git repo) uses the sibling vault `<parent>/x-memory/`.
If Claude Code is opened inside the vault itself, that is the vault.

Language: the vault's `.continuum.json` (`{"language": "es"}`) picks the labels of the text the CODE writes (routers, log).
Identifiers (folders, states, frontmatter keys) are always English.
"""
import json
import os
import re
import unicodedata
from pathlib import Path

SUFFIX = "-memory"
CONF_FILE = Path(".claude") / "claude-workbench.conf"
LANG_FILE = ".continuum.json"
DEFAULT_LANGUAGE = "en"

# Text the code writes without AI. Add a language by adding a block (same keys); no table -> English.
