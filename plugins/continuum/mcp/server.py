"""MCP "memory": reads and writes an Obsidian vault under fixed rules.

No dependencies: JSON-RPC 2.0 over stdio, standard library only.

Vault: by convention `../<project>-memory` next to the project's repo root (see vault.py).
    continuum.vault=<folder>   in .claude/claude-workbench.conf replaces it
    CONTINUUM_VAULT            replaces it too (for tests)

Rules enforced by the code, not by the model:
  - Nothing outside the vault; only .md; never hidden folders (.obsidian, .git).
  - Append only: there is no tool to delete or rewrite text.
    The only thing the code changes in place is the `status` of a task's frontmatter.
  - The routers (tasks/_router.md, decisions/_router.md) are regenerated by the code.
"""
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path

sys.dont_write_bytecode = True  # leave no __pycache__ in the plugin folder
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from vault import find_vault, label, slug, strip_accents, task_path  # noqa: E402

VERSION = "0.5.1"
STATES = ("open", "in progress", "done")
MODELS = ("opus", "sonnet", "haiku")
DEFAULT_ENTRIES = 5
MAX_RESULTS = 20
MAX_READ_CHARS = 20_000

VAULT = find_vault()


class UsageError(Exception):
    """Error returned to the model as text (does not break the server)."""


# ---------------------------------------------------------------- utilities

def now():
    return datetime.now()


def path_of(note):
    """'tasks/x' -> absolute Path validated inside the vault."""
    if not note or not isinstance(note, str):
        raise UsageError("Missing the note path (e.g. tasks/my-task).")
    rel = note.strip().replace("\\", "/").strip("/")
    if rel.endswith(".md"):
        rel = rel[:-3]
    if any(p.startswith(".") or p == "" for p in rel.split("/")):
        raise UsageError(f"Path not allowed: {note}")
    p = (VAULT / (rel + ".md")).resolve()
    if VAULT not in p.parents:
        raise UsageError(f"Path outside the vault: {note}")
    return p


def rel_of(p):
    return p.relative_to(VAULT).with_suffix("").as_posix()


def notes(folder=None):
    base = VAULT / folder if folder else VAULT
    if not base.is_dir():
        return []
    return sorted(p for p in base.rglob("*.md")
                  if not any(x.startswith(".") for x in p.relative_to(VAULT).parts))


def frontmatter(text):
    """Returns (dict, body). Simple `key: value` format."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end < 0:
        return {}, text
    data = {}
    for line in text[4:end].splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            data[k.strip()] = v.strip().strip('"')
    return data, text[end + 5:]


def with_frontmatter(data, body):
    lines = "\n".join(f"{k}: {v}" for k, v in data.items())
    return f"---\n{lines}\n---\n{body}"


def title_of(p, text):
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return p.stem


def write(p, text):
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(".md.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, p)


def append(p, text):
    with open(p, "a", encoding="utf-8") as f:
        f.write(text)


# ---------------------------------------------------------------- routers

def regenerate_routers():
    rows = []
    for p in notes("tasks"):
        if p.name.startswith("_"):
            continue
        text = p.read_text(encoding="utf-8")
        fm, _ = frontmatter(text)
        rows.append((fm.get("status", "?"), fm.get("updated", ""), rel_of(p), fm.get("last", ""),
                     fm.get("model", "")))
    lines = [f"# {label(VAULT, 'tasks_title')}", "", label(VAULT, "generated_tasks"), ""]
    for status in ("in progress", "open", "done"):
        group = [r for r in rows if r[0] == status]
        if not group:
            continue
        lines.append(f"## {status}")
        for _, date, rel, last, model in sorted(group, key=lambda r: r[1], reverse=True):
            nxt = f"→ {model}" if model and status != "done" else ""
            lines.append(" · ".join(x for x in (f"- [[{rel}]]", date, nxt, last) if x))
        lines.append("")
    write(VAULT / "tasks" / "_router.md", "\n".join(lines))

    decisions = [p for p in notes("decisions") if not p.name.startswith("_")]
    decisions.sort(key=lambda p: p.name, reverse=True)
    lines = [f"# {label(VAULT, 'decisions_title')}", "", label(VAULT, "generated_decisions"), ""]
    for p in decisions[:50]:
        text = p.read_text(encoding="utf-8")
        lines.append(f"- [[{rel_of(p)}]] · {title_of(p, text)}")
    write(VAULT / "decisions" / "_router.md", "\n".join(lines) + "\n")


# ---------------------------------------------------------------- tools

def t_search(text, folder=None):
    if not text or not text.strip():
        raise UsageError("Missing the text to search.")
    terms = strip_accents(text).split()
    results = []
    for p in notes(folder):
        if p.name.startswith("_"):  # routers: they repeat what the notes already say
            continue
        content = p.read_text(encoding="utf-8")
        rel = rel_of(p)
        haystack = strip_accents(rel + "\n" + content)
        if not all(t in haystack for t in terms):
            continue
        score = sum(haystack.count(t) for t in terms)
        line = next((l.strip() for l in content.splitlines()
                     if l.strip() and not l.startswith("---") and any(t in strip_accents(l) for t in terms)),
                    title_of(p, content))
        results.append((score, rel, line[:160]))
    if not results:
        return f"No results for «{text}»."
    results.sort(reverse=True)
    out = [f"- {rel} · {line}" for _, rel, line in results[:MAX_RESULTS]]
    extra = len(results) - MAX_RESULTS
    if extra > 0:
        out.append(f"(+{extra} more; narrow the search)")
    return "\n".join(out)


def t_read(note, full=False):
    p = path_of(note)
    if not p.exists():
        raise UsageError(f"Does not exist: {rel_of(p)}. Use search to find it.")
    text = p.read_text(encoding="utf-8")
    if not full and rel_of(p).startswith("tasks/"):
        parts = re.split(r"(?m)^(?=### \d{4}-\d{2}-\d{2} )", text)
        head, entries = parts[0], parts[1:]
        if len(entries) > DEFAULT_ENTRIES:
            omitted = len(entries) - DEFAULT_ENTRIES
            text = (head + f"\n_({omitted} earlier entries omitted; read with full=true)_\n\n"
                    + "".join(entries[-DEFAULT_ENTRIES:]))
    if len(text) > MAX_READ_CHARS:
        text = text[:MAX_READ_CHARS] + "\n\n_(cut: note too long)_"
    return text


def t_note(task, text, status=None, model=None, author=None, _moves_last=True):
    if not text or not text.strip():
        raise UsageError("Missing the text to note.")
    if status and status not in STATES:
        raise UsageError(f"Invalid status: {status}. Use: {', '.join(STATES)}.")
    model = model.strip().lower() if model else None
    if model and model not in MODELS:
        raise UsageError(f"Invalid model: {model}. Use: {', '.join(MODELS)}.")
    p = path_of(task_path(task))
    t = now()
    first_line = text.strip().splitlines()[0][:120]
    if p.exists():
        fm, body = frontmatter(p.read_text(encoding="utf-8"))
        created = False
    else:
        fm = {"status": "open", "created": f"{t:%Y-%m-%d}"}
        body = f"\n# {p.stem.replace('-', ' ').capitalize()}\n\n"
        created = True
    if status:
        fm["status"] = status
    if model:
        fm["model"] = model
    fm["updated"] = f"{t:%Y-%m-%d %H:%M}"
    if _moves_last or "last" not in fm:
        fm["last"] = first_line.replace(":", " -")
    write(p, with_frontmatter(fm, body))
    append(p, f"\n### {t:%Y-%m-%d %H:%M} · {author or 'claude'}\n{text.strip()}\n")
    regenerate_routers()
    return saved(p, "Created" if created else "Noted in")


def saved(p, action):
    """What ended up on disk (re-read, not what was asked): status, model and the last entry."""
    fm, body = frontmatter(p.read_text(encoding="utf-8"))
    last = re.split(r"(?m)^(?=### \d{4}-\d{2}-\d{2} )", body)[-1].strip()
    data = f"status: {fm.get('status', '?')} · model: {fm.get('model') or 'unset'}"
    return f"{action} [[{rel_of(p)}]] · {data}\nSaved:\n{last}"


def t_decide(title, text, task=None, author=None):
    if not title or not text:
        raise UsageError("Missing title or text.")
    t = now()
    base = f"decisions/{t:%Y-%m-%d}-{slug(title)}"
    p, n = path_of(base), 2
    while p.exists():
        p, n = path_of(f"{base}-{n}"), n + 1
    fm = {"date": f"{t:%Y-%m-%d %H:%M}", "author": author or "claude"}
    link = ""
    if task:
        rel_t = task_path(task)
        fm["task"] = f'"[[{rel_t}]]"'
        link = f"\nTask: [[{rel_t}]]\n"
    write(p, with_frontmatter(fm, f"\n# {title.strip()}\n{link}\n{text.strip()}\n"))
    if task:
        t_note(task, f"Decision: [[{rel_of(p)}]] — {title.strip()}", author=author, _moves_last=False)
    regenerate_routers()
    return f"Decision saved: [[{rel_of(p)}]]" + (f" · linked to [[{rel_t}]]" if task else "") + "."


TOOLS = {
    "search": (t_search, "Searches the memory. Returns paths and one line per note, not whole notes.", {
        "text": {"type": "string", "description": "words to look for (all must appear)"},
        "folder": {"type": "string", "description": "optional: tasks, decisions, log, agents"},
    }, ["text"]),
    "read": (t_read, "Reads a note by its path (e.g. tasks/x). For tasks it returns only the latest entries.", {
        "note": {"type": "string"},
        "full": {"type": "boolean", "description": "true for a task's whole history"},
    }, ["note"]),
    "note": (t_note, "Appends an entry at the end of a task (creates it if missing). Never rewrites.", {
        "task": {"type": "string", "description": "path or short name of the task"},
        "text": {"type": "string", "description": "what was done / where it stands; the 1st line is the summary"},
        "status": {"type": "string", "enum": list(STATES)},
        "model": {"type": "string", "enum": list(MODELS),
                  "description": "model that fits the next step of the task"},
        "author": {"type": "string", "description": "who notes (main agent or the subagent's name)"},
    }, ["task", "text"]),
    "decide": (t_decide, "Saves a decision as its own note and links it to its task.", {
        "title": {"type": "string"},
        "text": {"type": "string", "description": "what was decided and why"},
        "task": {"type": "string"},
        "author": {"type": "string"},
    }, ["title", "text"]),
}


# ---------------------------------------------------------------- protocol

def respond(id_, result=None, error=None):
    msg = {"jsonrpc": "2.0", "id": id_}
    if error:
        msg["error"] = error
    else:
        msg["result"] = result
    sys.stdout.write(json.dumps(msg, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def handle(msg):
    method, id_ = msg.get("method"), msg.get("id")
    params = msg.get("params") or {}
    if method == "initialize":
        respond(id_, {
            "protocolVersion": params.get("protocolVersion", "2025-06-18"),
            "capabilities": {"tools": {}},
            "serverInfo": {"name": "memory", "version": VERSION},
        })
    elif method == "ping":
        respond(id_, {})
    elif method == "tools/list":
        respond(id_, {"tools": [
            {"name": n, "description": d,
             "inputSchema": {"type": "object", "properties": props, "required": req}}
            for n, (_, d, props, req) in TOOLS.items()]})
    elif method == "tools/call":
        name = params.get("name")
        args = params.get("arguments") or {}
        if name not in TOOLS:
            respond(id_, error={"code": -32602, "message": f"Unknown tool: {name}"})
            return
        try:
            if VAULT is None or not VAULT.is_dir():
                raise UsageError(f"The vault {VAULT} does not exist. It is created by the init-project skill "
                                 "(or continuum.vault in .claude/claude-workbench.conf points to another folder).")
            text, is_error = TOOLS[name][0](**args), False
        except UsageError as e:
            text, is_error = str(e), True
        except TypeError as e:
            text, is_error = f"Invalid arguments: {e}", True
        except Exception as e:  # noqa: BLE001 - the server must not fall over
            text, is_error = f"Internal error: {type(e).__name__}: {e}", True
        respond(id_, {"content": [{"type": "text", "text": text}], "isError": is_error})
    elif id_ is not None:
        respond(id_, error={"code": -32601, "message": f"Method not supported: {method}"})
    # notifications (no id): ignored


def main():
    sys.stdin.reconfigure(encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            handle(json.loads(line))
        except json.JSONDecodeError:
            respond(None, error={"code": -32700, "message": "Invalid JSON"})


if __name__ == "__main__":
    main()
